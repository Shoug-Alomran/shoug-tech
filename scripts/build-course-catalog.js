#!/usr/bin/env node
"use strict";

/**
 * Builds docs/data/course-catalog.json for the schedule planner and its
 * advisor (Murshid). One entry per course code, merged from:
 *
 *   docs/academic-plan-themes/<plan>/grid.html   COURSES: names, hours, prereqs,
 *                                                minHours, plan term
 *   docs/academic-plan-themes/course-syllabi.json chapters + assessment weights
 *   docs/academics/<track>/<code>/index.html     the course page on this site
 *
 * Rerun after editing a plan grid or the syllabi file.
 */

const fs = require("fs");
const path = require("path");
const vm = require("vm");

const ROOT = path.join(__dirname, "..");
const PLANS_DIR = path.join(ROOT, "docs", "academic-plan-themes");
const ACADEMICS = path.join(ROOT, "docs", "academics");
const OUT = path.join(ROOT, "docs", "data", "course-catalog.json");

function arrayLiteral(source, name) {
  const start = source.indexOf(`const ${name} = [`);
  if (start < 0) return null;
  let i = source.indexOf("[", start);
  const from = i;
  let depth = 0;
  let quote = null;
  for (; i < source.length; i++) {
    const ch = source[i];
    if (quote) {
      if (ch === "\\") i++;
      else if (ch === quote) quote = null;
      continue;
    }
    if (ch === '"' || ch === "'" || ch === "`") quote = ch;
    else if (ch === "/" && source[i + 1] === "/") i = source.indexOf("\n", i);
    else if (ch === "[") depth++;
    else if (ch === "]" && --depth === 0) break;
  }
  return vm.runInNewContext(`(${source.slice(from, i + 1)})`, {});
}

const termOrder = (term) => {
  const m = String(term || "").match(/^t(\d+)$/);
  return m ? +m[1] : String(term).startsWith("prep") ? 0 : null;
};

const catalog = {};

for (const plan of fs.readdirSync(PLANS_DIR)) {
  const grid = path.join(PLANS_DIR, plan, "grid.html");
  if (!fs.existsSync(grid)) continue;
  const courses = arrayLiteral(fs.readFileSync(grid, "utf8"), "COURSES");
  if (!courses) continue;
  for (const c of courses) {
    if (!c || !c.code) continue;
    const code = c.code.replace(/\s+/g, "").toUpperCase();
    const entry = (catalog[code] ||= { pre: [], plans: {} });
    if (c.nameEn && !entry.en) entry.en = c.nameEn;
    if (c.name && !entry.ar) entry.ar = c.name;
    if (c.hours != null && entry.h == null) entry.h = c.hours;
    if (c.minHours) entry.minHours = Math.max(entry.minHours || 0, c.minHours);
    for (const p of c.prereqs || []) {
      const pc = String(p).replace(/\s+/g, "").toUpperCase();
      if (!entry.pre.includes(pc)) entry.pre.push(pc);
    }
    const order = termOrder(c.term);
    if (order != null) entry.plans[plan] = order;
  }
}

// Which courses unlock which: the reverse of prereqs.
for (const [code, entry] of Object.entries(catalog)) {
  for (const p of entry.pre) {
    if (!catalog[p]) continue;
    (catalog[p].unlocks ||= []).includes(code) || catalog[p].unlocks.push(code);
  }
}

const syllabi = JSON.parse(
  fs.readFileSync(path.join(PLANS_DIR, "course-syllabi.json"), "utf8"),
);
for (const [code, s] of Object.entries(syllabi)) {
  if (code.startsWith("_")) continue;
  const entry = (catalog[code] ||= { pre: [], plans: {} });
  entry.chapters = (s.chapters || []).map((ch) => ch.title);
  entry.assess = (s.items || []).map((it) => [
    it.title,
    it.weight,
    it.exam ? 1 : 0,
  ]);
}

for (const track of fs.readdirSync(ACADEMICS)) {
  const dir = path.join(ACADEMICS, track);
  if (!fs.statSync(dir).isDirectory()) continue;
  const scan = (base, prefix) => {
    for (const name of fs.readdirSync(base)) {
      if (!/^[a-z]+\d{3}$/.test(name)) {
        if (name === "english")
          scan(path.join(base, name), `${prefix}english/`);
        continue;
      }
      if (!fs.existsSync(path.join(base, name, "index.html"))) continue;
      const code = name.toUpperCase();
      const entry = (catalog[code] ||= { pre: [], plans: {} });
      entry.url ||= `/academics/${track}/${prefix}${name}/`;
    }
  };
  scan(dir, "");
}

const sorted = {};
for (const code of Object.keys(catalog).sort()) {
  const e = catalog[code];
  if (!e.pre.length) delete e.pre;
  if (!Object.keys(e.plans).length) delete e.plans;
  sorted[code] = e;
}

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(
  OUT,
  JSON.stringify({
    _note:
      "Generated by scripts/build-course-catalog.js from the plan grids, course-syllabi.json and the course pages. Do not edit by hand.",
    courses: sorted,
  }),
);
console.log(
  `Wrote ${Object.keys(sorted).length} courses to ${path.relative(ROOT, OUT)}`,
);
