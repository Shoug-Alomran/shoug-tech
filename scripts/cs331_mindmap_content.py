"""Deep CS331 mind-map content (one tree per chapter).

Node helper: N(title, summary, *children, d=html)
  - summary: short line shown on the node card (keep it under ~100 chars)
  - d: optional richer HTML shown in the side panel when a leaf is clicked
Branches that "diverge into types / also-called names" are modelled as real
child nodes so they are visible on the map, not hidden in the panel text.
"""


def N(t, s, *k, d=None):
    return {"t": t, "s": s, "k": list(k), "d": d}


def ul(*items):
    return "<ul>" + "".join(f"<li>{i}</li>" for i in items) + "</ul>"


