"""Chapter quizzes for the CYS401 decks that had none: 3, 4, 8, 9 and 10.

Written from the lecture PDFs in docs/academics/cybersecurity/cys401/slides/, and
shaped like the past papers: scenario MCQs, matching, fill-ins and short answers.
Chapter numbers follow the decks' own titles. The file names of the last two decks
do not: chapter-9-systems-architecture-security.pdf is the ICS/SCADA deck and
chapter-10-ics-and-scada-system-security.pdf is Authentication and Access Control.

M() takes the keyed answer first; options are shuffled with a seed from the
question text, so the correct letter does not follow a pattern.
"""

import hashlib
import random


def M(q, correct, wrong, why):
    """An MCQ. `wrong` is a list of (distractor, why it is wrong)."""
    options = [correct] + [w[0] for w in wrong]
    random.Random(hashlib.sha256(q.encode()).hexdigest()).shuffle(options)
    return {
        "type": "mcq", "q": q, "options": options, "correct": options.index(correct), "why": why,
        "wrong": {options.index(text): reason for text, reason in wrong},
    }


def F(q, accept, answer, why):
    return {"type": "fill", "q": q, "accept": accept, "answer": answer, "why": why}


def T(q, options, items):
    """Matching. Each item is (prompt, answer from options, explanation)."""
    return {"type": "match", "q": q, "options": options, "items": [list(i) for i in items]}


def S(q, concepts, answer, why):
    return {"type": "short", "q": q, "concepts": concepts, "answer": answer, "why": why}


def quiz(number, slug, item, topic, intro, sections):
    questions = sum(len(s["questions"]) for s in sections)
    return {
        "slug": slug,
        "file": f"chapter-{number}-quiz.html",
        "title": f"Chapter {number} Quiz",
        "item": item,
        "meta": f"Practice quiz · {topic} · {questions} questions",
        "intro": intro,
        "footer": "Practice questions written from this chapter's slides in the style of the "
                  "past papers. This is not an official paper.",
        "sections": sections,
    }


