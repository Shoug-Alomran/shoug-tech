#!/usr/bin/env python3
"""Map renamed academic page URLs to where they live now.

Progress ("mark complete") is stored per page URL, so renaming or renumbering
a page orphans everyone's completion for it. This reads the page renames in
git history and writes docs/javascripts/url-moves.js, which the progress
pages use to carry old completions over to the current URL.

A rename is kept only when it is safe: same track, course and section; the
old page no longer exists; the final destination is a current course page;
and the page name is unchanged apart from a number prefix or a hash suffix
(so renumbered chapters move, but two similar pages are never swapped). Re-run after reorganizing a course:

    python3 scripts/build_url_moves.py
"""
from __future__ import annotations

import json
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DOCS = ROOT / "docs"
OUT = DOCS / "javascripts" / "url-moves.js"


def url(path: str) -> str:
    return "/" + path[len("docs/") : -len("index.html")]


def slug(u: str) -> str:
    name = u.rstrip("/").split("/")[-1]
    return re.sub(r"-[0-9a-f]{8}$", "", re.sub(r"^\d+[-_]", "", name))


def main() -> int:
    log = subprocess.run(
        ["git", "log", "--reverse", "--diff-filter=R", "-M", "--name-status", "--format=", "--", "docs/academics"],
        cwd=ROOT, capture_output=True, text=True, check=True,
    ).stdout
    manifest = (DOCS / "javascripts" / "course-manifest.js").read_text(encoding="utf-8")
    current = set(re.findall(r'url: "([^"]+)"', manifest))

    moves: dict[str, str] = {}
    for line in log.splitlines():
        parts = line.split("\t")
        if len(parts) != 3 or not parts[0].startswith("R"):
            continue
        old, new = parts[1], parts[2]
        if not (old.endswith("/index.html") and new.endswith("/index.html")):
            continue
        a, b = url(old), url(new)
        if a.split("/")[2:5] != b.split("/")[2:5] or len(a.split("/")) < 6:
            continue
        if slug(a) != slug(b):
            continue
        moves[a] = b

    def final(u: str) -> str:
        seen = set()
        while u in moves and u not in seen:
            seen.add(u)
            u = moves[u]
        return u

    result = {}
    for old in moves:
        dest = final(old)
        if (DOCS / old.lstrip("/") / "index.html").exists() or dest not in current or dest == old:
            continue
        result[old] = dest

    OUT.write_text(
        "// Auto-generated by scripts/build_url_moves.py - do not edit by hand.\n"
        "// Old academic page URL -> current URL, so completions survive renames.\n"
        "var SHOUG_URL_MOVES = " + json.dumps(dict(sorted(result.items())), indent=2) + ";\n",
        encoding="utf-8",
    )
    print(f"Wrote {OUT.relative_to(ROOT)} with {len(result)} moves")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
